"""
Запускає цей самий Flask-додаток БЕЗ pywebview-вікна, доступним по локальній
Wi-Fi мережі - щоб відкрити його в Safari на iPhone (або будь-якому іншому
пристрої в тій самій мережі) і додати на головний екран як застосунок
("Поділитися" -> "На екран "Домій"").

Навмисно окремий файл, а не новий режим app.py: app.py лишається
незмінним (і далі відкриває pywebview-вікно при "python app.py"), а цей
файл просто імпортує вже готовий Flask-додаток (`app` з app.py,
створений через create_app()) і піднімає його на 0.0.0.0 - тобто на всіх
мережевих інтерфейсах цього комп'ютера, а не лише на localhost.

Телефон і цей комп'ютер мають бути в одній Wi-Fi мережі. При першому
запуску Windows, скоріш за все, спитає дозвіл через Брандмауер Windows
("Windows Defender Firewall") - треба дозволити доступ для приватних
мереж (Private networks), інакше телефон не зможе достукатись.
"""
import socket

from app import app as flask_app

PORT = 5000


def get_local_ip():
    """
    Локальна IP-адреса цього комп'ютера в поточній мережі (напр.
    192.168.1.23). Трюк без реального мережевого запиту: "підключаємось"
    по UDP до публічної адреси (нічого фактично не надсилається), і ОС
    підбирає вихідний мережевий інтерфейс - з нього й беремо IP. Якщо
    мережі немає взагалі, тихо повертаємось до localhost.
    """
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        s.connect(("8.8.8.8", 80))
        return s.getsockname()[0]
    except OSError:
        return "127.0.0.1"
    finally:
        s.close()


if __name__ == "__main__":
    ip = get_local_ip()
    url = f"http://{ip}:{PORT}"

    print("=" * 56)
    print("  music_app працює у вашій Wi-Fi мережі")
    print("=" * 56)
    print(f"  Відкрийте на телефоні (той самий Wi-Fi):\n\n      {url}\n")
    print("  Потім у Safari: кнопка 'Поділитися' -> 'На екран Домій',")
    print("  щоб отримати іконку застосунку.")
    print()
    print("  Якщо Windows запитає про доступ у брандмауері - дозвольте")
    print("  для приватних мереж (Private networks).")
    print("=" * 56)

    flask_app.run(host="0.0.0.0", port=PORT, threaded=True)
